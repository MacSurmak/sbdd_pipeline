"""
File: cli/commands/rescore.py
Description: CLI handler for 'sbdd rescore': standalone Prime MM-GBSA and Consensus rescoring.
"""

import csv
import json
import sys
from pathlib import Path
from rich.console import Console
from rich.table import Table
from cli.core.db import init_db, Target, ReceptorFrame, Pose, System
from cli.core.runner import execute_nextflow
from cli.core.config_loader import load_project_configs, build_nextflow_args

console = Console()


def run_rescore(
    use_whitelist: bool = False,
    urgent: bool = False,
    local: bool = False,
    resume: bool = True,
) -> None:
    """Runs standalone Prime MM-GBSA and Consensus rescoring."""
    cwd = Path.cwd()
    session = init_db()

    # Query ready ReceptorFrames directly from SQLite (SSOT)
    ready_frames = session.query(ReceptorFrame).filter_by(state="ready").all()
    if not ready_frames:
        console.print(
            "[bold red]FATAL: No ready ReceptorFrame entities found in database. Run 'sbdd prep' first.[/bold red]"
        )
        session.close()
        sys.exit(1)

    tasks = []
    dock_summary_files = set()

    for frame in ready_frames:
        # Strict SSOT: Only process frames that have actual docking poses registered in the DB
        docked_poses = (
            session.query(Pose)
            .filter(Pose.receptor_frame_id == frame.id, Pose.origin.like("docking_%"))
            .all()
        )

        if not docked_poses:
            continue

        frame_dir = (cwd / "docking" / frame.name).resolve()
        pv_file = frame_dir / f"{frame.name}_dock_pv.maegz"

        tasks.append({"name": frame.name, "pv_path": str(pv_file), "frame": frame.name})

        expected_artifacts = [
            frame_dir / f"{frame.name}_dock.csv",
            frame_dir / f"{frame.name}_dock.sdf",
            frame_dir / f"{frame.name}_rescored.sdf",
            frame_dir / f"{frame.name}_glide_rmsd.csv",
            frame_dir / f"{frame.name}_gnina_docked_all.sdf",
            frame_dir / f"{frame.name}_gnina_rmsd.csv",
        ]
        for art in expected_artifacts:
            dock_summary_files.add(str(art))

    if not tasks:
        console.print(
            "[bold red]FATAL: No Pose Viewer artifacts found for registered ready frames in docking/<frame>/. Run 'sbdd dock' first.[/bold red]"
        )
        session.close()
        sys.exit(1)

    # Determine reference native ligand strictly from database
    native_ligand_name = ""
    for s in session.query(System).all():
        if s.pose and s.pose.origin == "crystal":
            native_ligand_name = s.pose.ligand.name
            break

    dock_plan_file = cwd / "dock_plan.json"
    if dock_plan_file.exists():
        dock_summary_files.add(str(dock_plan_file.resolve()))

    whitelist_csv = cwd / "funnel_whitelist.csv"
    plan = {
        "use_whitelist": use_whitelist,
        "whitelist_path": (
            str(whitelist_csv.resolve()) if whitelist_csv.exists() else ""
        ),
        "dock_summary_files": sorted(list(dock_summary_files)),
        "tasks": tasks,
    }

    plan_file = cwd / "rescore_plan.json"
    with open(plan_file, "w", encoding="utf-8") as f:
        json.dump(plan, f, indent=2)

    console.print(
        f"[bold cyan]Generated rescore_plan.json for {len(tasks)} target frame(s) with {len(dock_summary_files)} docking artifact(s)...[/bold cyan]"
    )

    configs = load_project_configs(cwd)
    nf_args = build_nextflow_args(configs, cwd, entrypoint="rescore")
    nf_args.extend(["--rescore_plan", str(plan_file.resolve())])

    if native_ligand_name:
        if "--native_ligand" in nf_args:
            idx = nf_args.index("--native_ligand")
            nf_args[idx + 1] = native_ligand_name
        else:
            nf_args.extend(["--native_ligand", native_ligand_name])

    if urgent:
        nf_args.extend(["--queue", "urgent"])

    profile_name = "local" if local else "slurm"

    ret_code = execute_nextflow(
        "rescore", nf_args, cwd, profile=profile_name, resume=resume, configs=configs
    )

    if ret_code != 0:
        session.close()
        console.print("[bold red]Nextflow MM-GBSA rescoring failed.[/bold red]")
        sys.exit(ret_code)

    # Atomically synchronize results into SQLite strictly via rescore_receipt.tsv
    receipt_file = cwd / "rescore_receipt.tsv"
    if not receipt_file.exists() or receipt_file.stat().st_size == 0:
        session.close()
        raise FileNotFoundError(
            f"FATAL: Execution receipt {receipt_file} was not generated by orchestrator. "
            "Database update aborted."
        )

    res_csv = cwd / "reports" / "ranking.csv"
    if not res_csv.exists() or res_csv.stat().st_size == 0:
        session.close()
        raise FileNotFoundError(
            f"FATAL: Consolidated ranking {res_csv} is missing. Process aborted."
        )

    with open(res_csv, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            title = row.get("Title", "").strip()
            frame_name = row.get("Receptor", row.get("Frame", "")).strip()
            if not title or not frame_name:
                continue

            pose_name = f"{frame_name}_{title}_dock"
            scores_dict = {
                k: float(v)
                for k, v in row.items()
                if k not in ["Rank", "Title", "Receptor", "Frame"]
                and v
                and v != "nan"
                and v != ""
            }

            pose_obj = session.query(Pose).filter_by(name=pose_name).first()
            if pose_obj:
                pose_obj.scores_dict = scores_dict

    session.commit()
    session.close()

    # Render summary results table
    table = Table(title="🎯 Post-Rescore Consensus Ranking Summary", show_header=True)
    table.add_column("Receptor", style="cyan")
    table.add_column("Ligand", style="bold")
    table.add_column("GlideScore", justify="right")
    table.add_column("CNN Affinity", justify="right")
    table.add_column("MM-GBSA (kcal/mol)", justify="right", style="bold magenta")
    table.add_column("Glide RMSD (Å)", justify="center")
    table.add_column("GNINA RMSD (Å)", justify="center")
    table.add_column("Verdict", justify="center")

    with open(res_csv, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            rec = row.get("Receptor", row.get("Frame", "-"))
            lig = row.get("Title", "-")
            gscore = row.get("GlideScore", "-")
            cnn = row.get("Resc_CNNaffinity") or row.get("Dock_CNNaffinity") or "-"
            mmgbsa = row.get("MMGBSA", "-")
            g_rmsd = row.get("InSitu_RMSD_Glide_A", "-")
            n_rmsd = row.get("InSitu_RMSD_GNINA_A", "-")

            def _fmt(val):
                try:
                    return f"{float(val):.2f}"
                except (ValueError, TypeError):
                    return str(val) if val and val != "nan" else "-"

            def _color_rmsd(val_str):
                if val_str and val_str not in ["nan", "-"]:
                    try:
                        v = float(val_str)
                        return (
                            f"[bold green]{v:.2f}[/bold green]"
                            if v <= 2.0
                            else f"[bold red]{v:.2f}[/bold red]"
                        )
                    except ValueError:
                        return val_str
                return "-"

            verdict = "[dim]-[/dim]"
            try:
                vg = float(g_rmsd) if g_rmsd and g_rmsd not in ["nan", "-"] else None
                vn = float(n_rmsd) if n_rmsd and n_rmsd not in ["nan", "-"] else None
                if (vg is not None and vg <= 2.5) or (vn is not None and vn <= 2.5):
                    verdict = "[bold green]✓ SUCCESS[/bold green]"
                elif vg is not None or vn is not None:
                    verdict = "[bold yellow]⚠ DRIFT[/bold yellow]"
            except ValueError:
                pass

            table.add_row(
                rec,
                lig,
                _fmt(gscore),
                _fmt(cnn),
                _fmt(mmgbsa),
                _color_rmsd(g_rmsd),
                _color_rmsd(n_rmsd),
                verdict,
            )

    console.print(table)
    console.print(
        "\n[bold green]✓ Prime MM-GBSA rescoring completed and synchronized with SQLite database![/bold green]\n"
    )
